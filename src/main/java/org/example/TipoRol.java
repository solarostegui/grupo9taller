package org.example;

/**
 * Define el rol del cuepo técnico y médicos que asisten a los jugadores.
 * @author María del Mar Dalorso, Antonella Monti.
 * @version 1.0
 */
public enum TipoRol {
    /**
     * El asistente directo del director técnico principal.
     */
    AyudanteCampo,
    /**
     * El encargado de preparar físicamente a los jugadores y controlar que estén en ritmo.
     */
    PreparadorFisico,
    /**
     * El doctor principal encargado de la salud general de toda la delegación.
     */
    Medico,
    /**
     * Encargado de la kinesiología, masajes y recuperación de molestias físicas.
     */
    Kinesiologo,
    /**
     * Entrenador especialista en el trabajo diario con los arqueros.
     */
    EntrenadorArqueros,
    /**
    * El encargado de filmar y analizar los videos de los rivales y del propio equipo para armar la táctica.
    */
    AnalistaVideos,
    /**
     * El encargado de planificar las comidas y la dieta de los futbolistas.
     */
    Nutricionista,
    /**
     * El profesional encargado del bienestar mental y la motivación del plantel.
     */
    Psicologo
}
